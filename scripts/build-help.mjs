// Bundle canonical public guides and local images for offline Tauri assets.
import fs from "node:fs/promises";
import { HELP_CATALOG } from "../viewer/help-catalog.mjs";
const root = new URL("../", import.meta.url);
const guides = await Promise.all(
  HELP_CATALOG.map(async (guide) => {
    const markdown = await fs.readFile(new URL(guide.source, root), "utf8"),
      images = {};
    for (const match of markdown.matchAll(/!\[[^\]]*\]\(([^)]+)\)/g)) {
      if (!/\.(png|jpe?g|gif)$/i.test(match[1]) || /^[a-z]+:/i.test(match[1]))
        continue;
      const bytes = await fs.readFile(
        new URL(match[1], new URL(guide.source, root)),
      );
      const type = /\.png$/i.test(match[1])
        ? "png"
        : /\.gif$/i.test(match[1])
          ? "gif"
          : "jpeg";
      images[match[1]] =
        `data:image/${type};base64,${bytes.toString("base64")}`;
    }
    return { ...guide, markdown, images };
  }),
);
await fs.writeFile(
  new URL("viewer/help-content.mjs", root),
  "// Generated by scripts/build-help.mjs from the public user guides.\nexport const HELP_GUIDES = " +
    JSON.stringify(guides, null, 2) +
    ";\n",
);
console.log(`Bundled ${guides.length} offline help guides.`);
