"""Build the offline catalog from factual vendor-table extracts (no network).

Usage: python3 scripts/build-enzyme-catalog.py
See data/restriction-enzymes/README.md for source URLs and extraction details.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/restriction-enzymes'

def canonical(name):
    return re.sub(r'-(?:HFv?2?|v2)$', '', name)

def parse_cut(notation):
    notation = re.sub(r'\(N\)(\d+)', lambda m: 'N' * int(m[1]), notation.replace('^', '/'))
    if notation.startswith('/') and re.fullmatch(r'/[ACGTRYSWKMBDHVN]+', notation):
        return notation[1:], 0, len(notation)-1, ''
    if re.fullmatch(r'[ACGTRYSWKMBDHVN]*/[ACGTRYSWKMBDHVN]*', notation):
        site = notation.replace('/', '')
        top = notation.index('/')
        return site, top, len(site)-top, ''
    m = re.fullmatch(r'([ACGTRYSWKMBDHVN]+)\((-?\d+)/(-?\d+)\)/?', notation)
    if m:
        return m[1], len(m[1])+int(m[2]), len(m[1])+int(m[3]), ''
    site = re.search(r'[ACGTRYSWKMBDHVN]{2,}', notation)
    if not site:
        raise ValueError(notation)
    reason = 'Nickase: single-strand cleavage is not simulated.' if 'none' in notation else 'Complex or variable cleavage: recognition only; digest is not simulated.'
    return site[0], None, None, reason

rows = json.loads((DATA / 'vendor-facts.json').read_text())
enzymes = {}
for row in rows:
    name = canonical(row['name'])
    notation = row['notation']
    # Two unmarked entries in the NEB alphabetized chart; same specificity as
    # Esp3I / blunt GTATAC, respectively, independently cross-checked in REBASE.
    if name == 'BsmBI' and notation == 'CGTCTC': notation = 'CGTCTC(1/5)'
    if name == 'BstZ17I' and notation == 'GTATAC': notation = 'GTA/TAC'
    site, top, bottom, reason = parse_cut(notation)
    existing = enzymes.get(name)
    if existing and (existing['recognition'], existing['top'], existing['bottom']) != (site, top, bottom):
        raise ValueError(f'Conflicting vendor cleavage for {name}: {existing} / {row}')
    e = enzymes.setdefault(name, dict(name=name, recognition=site, top=top, bottom=bottom, vendors=[], aliases=[], products=[], notation=notation, limitation=reason))
    if row['vendor'] not in e['vendors']: e['vendors'].append(row['vendor'])
    if row['name'] != name and row['name'] not in e['aliases']: e['aliases'].append(row['name'])
    product = {k: row[k] for k in ('vendor', 'name', 'source')}
    product['name'] = row.get('productName', row['name'])
    if product['name'] != name and product['name'] not in e['aliases']: e['aliases'].append(product['name'])
    e['products'].append(product)

# Conservative workflow support: explicit 3/4-base 5′ Type IIS enzymes with
# downstream cuts. Other Type IIS enzymes remain available for site analysis.
golden = set('BsaI BsmBI BbsI SapI Esp3I Eco31I BpiI BspQI LguI PaqCI AarI BfuAI BspMI BsmAI BcoDI EarI Eam1104I BveI'.split())
dependent = {'DpnI', 'MspJI', 'FspEI', 'LpnPI', 'SgeI', 'EcoP15I', 'McrBC'}
for e in enzymes.values():
    if e['name'].startswith(('Nt.', 'Nb.')):
        e['limitation'] = 'Nickase: single-strand cleavage is not simulated.'
    if e['name'] in dependent:
        e['limitation'] = 'Requires methylation and/or paired-site context: recognition only; digest is not simulated.'
    if e['name'] == 'PspFI':
        e['limitation'] = 'Vendor FastDigest chart and REBASE disagree on strand cut offsets: recognition only pending confirmation.'
    e['digestible'] = not bool(e['limitation'])
    e['typeIIS'] = e['top'] is not None and e['top'] >= len(e['recognition']) and e['bottom'] >= len(e['recognition']) and e['recognition'] != e['recognition'].translate(str.maketrans('ACGTRYSWKMBDHVN', 'TGCAYRSWMKVHDBN'))[::-1] and e['name'] != 'EcoP15I'
    if e['name'] in dependent: e['typeIIS'] = False
    e['goldenGate'] = e['name'] in golden and e['digestible'] and e['typeIIS'] and e['bottom']-e['top'] in (3,4)
    if e['name'] in {'AarI', 'PaqCI'}:
        e['reactionNote'] = 'Requires the vendor-specified activator oligonucleotide; verify the product-specific assembly protocol.'
    elif e['goldenGate']:
        e['reactionNote'] = 'Sequence/end prediction only. Use the product-specific temperature, buffer and ligase protocol; formulations are not interchangeable reaction recipes.'
ordered = sorted(enzymes.values(), key=lambda e:e['name'].lower())
output = '// Generated by scripts/build-enzyme-catalog.py. Source facts and coverage: data/restriction-enzymes/.\n'
output += 'export const ENZYME_CATALOG = ' + json.dumps(ordered, indent=2, ensure_ascii=False) + ';\n'
output += 'export const GOLDEN_GATE_ENZYMES = ENZYME_CATALOG.filter(e => e.goldenGate);\n'
output += 'export function findEnzyme(name) { return ENZYME_CATALOG.find(e => e.name === name || e.aliases.includes(name)); }\n'
(ROOT / 'viewer/enzyme-catalog.mjs').write_text(output)
print(f'{len(ordered)} enzymes; {sum(e["digestible"] for e in ordered)} modeled digests; {sum(e["goldenGate"] for e in ordered)} Golden Gate choices')
